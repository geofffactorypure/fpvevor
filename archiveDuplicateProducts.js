async function getStoreInfo() {
    const rows = await query(`SELECT * FROM stores WHERE id = ?`, [STORE_ID])
    return rows[0]
}

async function shopifyGraphQL(storeInfo, queryStr, variables = {}) {
    const res = await fetch(`https://${storeInfo.shopify_name}.myshopify.com/admin/api/${API_VERSION}/graphql.json`, {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json',
            'X-Shopify-Access-Token': storeInfo.access_token,
        },
        body: JSON.stringify({ query: queryStr, variables }),
    })
    const json = await res.json()
    if (json.errors) {
        throw new Error(`GraphQL errors: ${JSON.stringify(json.errors)}`)
    }
    return json.data
}

function sleep(ms) {
    return new Promise((resolve) => setTimeout(resolve, ms))
}

async function getVariantsForProduct(storeInfo, productId) {
    const gql = `
        query getProduct($id: ID!) {
            product(id: $id) {
                id
                title
                variants(first: 100) {
                    nodes {
                        id
                        sku
                        metafields(first: 20, namespace: "custom") {
                            nodes {
                                key
                                value
                            }
                        }
                    }
                }
            }
        }
    `
    const data = await shopifyGraphQL(storeInfo, gql, {
        id: `gid://shopify/Product/${productId}`,
    })
    return data.product
}

async function updateVariantSkuAndArchive(storeInfo, productId, variants) {
    // Step 1: Update variant SKUs via productVariantsBulkUpdate
    const variantInputs = variants.map((v) => ({
        id: v.id,
        inventoryItem: {
            sku: v.sku ? `${v.sku}-DUPLICATE` : v.sku,
        },
    }))

    const bulkUpdateMutation = `
        mutation productVariantsBulkUpdate($productId: ID!, $variants: [ProductVariantsBulkInput!]!) {
            productVariantsBulkUpdate(productId: $productId, variants: $variants) {
                userErrors { field message }
            }
        }
    `
    const bulkResult = await shopifyGraphQL(storeInfo, bulkUpdateMutation, {
        productId: `gid://shopify/Product/${productId}`,
        variants: variantInputs,
    })
    if (bulkResult.productVariantsBulkUpdate.userErrors.length > 0) {
        console.error(`  SKU update errors for product ${productId}:`, bulkResult.productVariantsBulkUpdate.userErrors)
    } else {
        console.log(`  Updated SKUs for product ${productId}`)
    }

    // Step 2: Update metafields (supplier_sku, supplier_model_number, upc)
    const metafieldKeys = ['supplier_sku', 'supplier_model_number', 'upc']
    const metafields = []
    for (const variant of variants) {
        for (const key of metafieldKeys) {
            const existing = variant.metafields.nodes.find((m) => m.key === key)
            if (existing && existing.value) {
                metafields.push({
                    ownerId: variant.id,
                    namespace: 'custom',
                    key,
                    type: 'single_line_text_field',
                    value: `${existing.value}-DUPLICATE`,
                })
            }
        }
    }

    if (metafields.length > 0) {
        const metafieldsMutation = `
            mutation metafieldsSet($metafields: [MetafieldsSetInput!]!) {
                metafieldsSet(metafields: $metafields) {
                    userErrors { field message }
                }
            }
        `
        const metaResult = await shopifyGraphQL(storeInfo, metafieldsMutation, { metafields })
        if (metaResult.metafieldsSet.userErrors.length > 0) {
            console.error(`  Metafield update errors for product ${productId}:`, metaResult.metafieldsSet.userErrors)
        } else {
            console.log(`  Updated metafields for product ${productId}`)
        }
    }

    // Step 3: Archive the product
    const archiveMutation = `
        mutation productUpdate($input: ProductInput!) {
            productUpdate(input: $input) {
                product { id status }
                userErrors { field message }
            }
        }
    `
    const archiveResult = await shopifyGraphQL(storeInfo, archiveMutation, {
        input: {
            id: `gid://shopify/Product/${productId}`,
            status: 'ARCHIVED',
        },
    })
    if (archiveResult.productUpdate.userErrors.length > 0) {
        console.error(`  Archive errors for product ${productId}:`, archiveResult.productUpdate.userErrors)
    } else {
        console.log(`  Archived product ${productId}`)
    }
}

async function updateLocalDB(productId, variants) {
    for (const variant of variants) {
        // Extract numeric variant ID from GID
        const variantId = variant.id.replace('gid://shopify/ProductVariant/', '')
        await query(
            `UPDATE variants_new 
             SET sku = CONCAT(IFNULL(sku, ''), '-DUPLICATE'),
                 custom_supplier_sku = CONCAT(IFNULL(custom_supplier_sku, ''), '-DUPLICATE'),
                 custom_supplier_model_number = CONCAT(IFNULL(custom_supplier_model_number, ''), '-DUPLICATE'),
                 custom_upc = CONCAT(IFNULL(custom_upc, ''), '-DUPLICATE')
             WHERE id = ? AND store_id = ?`,
            [variantId, STORE_ID]
        )
    }
    console.log(`  Updated local DB for product ${productId}`)
}

async function main() {
    const storeInfo = await getStoreInfo()
    console.log(`Store: ${storeInfo.shopify_name}`)
    console.log(`Processing ${duplicates.length} duplicate group(s)\n`)

    for (const dup of duplicates) {
        const allIds = dup.all_product_ids.split(',').map(Number)
        // Keep the oldest (smallest ID), archive the rest
        const oldest = Math.min(...allIds)
        const toArchive = allIds.filter((id) => id !== oldest)

        console.log(`\nGroup: SKU=${dup.custom_supplier_sku}`)
        console.log(`  Keeping product ${oldest}`)
        console.log(`  Archiving: ${toArchive.join(', ')}`)

        for (const productId of toArchive) {
            try {
                const product = await getVariantsForProduct(storeInfo, productId)
                if (!product) {
                    console.error(`  Product ${productId} not found on Shopify, skipping.`)
                    continue
                }
                const variants = product.variants.nodes
                await updateVariantSkuAndArchive(storeInfo, productId, variants)
                await updateLocalDB(productId, variants)
                // Rate limit: ~2 requests per second
                await sleep(500)
            } catch (err) {
                console.error(`  Error processing product ${productId}:`, err.message)
            }
        }
    }

    console.log('\nDone!')
    pool.end()
}

main().catch((err) => {
    console.error('Fatal error:', err)
    pool.end()
    process.exit(1)
})
